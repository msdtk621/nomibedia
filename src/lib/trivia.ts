/**
 * 日付をもとに日替わりで選ぶ。
 * ランダムだとサーバーとクライアントで結果がずれてハイドレーションが壊れるため、
 * 日付から決まる値を使って毎回同じ結果になるようにしている。
 * count 件を重複なしで返す（一覧より多く要求されたら全件で頭打ち）。
 */
export function getDailyTrivia(count = 1, date = new Date()): Trivia[] {
  const days = Math.floor(date.getTime() / 86_400_000)
  const len = triviaList.length
  const n = Math.min(count, len)
  // 一覧はカテゴリ順に並んでいるため、隣り合う要素を取ると同じカテゴリばかりになる。
  // リスト全体を n 等分した間隔で拾い、毎日ずらすことで種類が散るようにしている。
  const stride = Math.max(1, Math.floor(len / n))
  return Array.from({ length: n }, (_, i) => triviaList[(days + i * stride) % len])
}
