export function getTrivia(slug: string): Trivia | undefined {
  return triviaList.find((t) => t.slug === slug)
}

/**
 * 日付をもとに日替わりで選ぶ。
 * ランダムだとサーバーとクライアントで結果がずれてハイドレーションが壊れるため、
 * 日付から決まる値を使って毎回同じ結果になるようにしている。
 * count 件を重複なしで返す（一覧より多く要求されたら全件で頭打ち）。
 */
export function getDailyTrivia(count = 1, date = new Date()): Trivia[] {
  const days = Math.floor(date.getTime() / 86_400_000)
  const n = Math.min(count, triviaList.length)
  return Array.from({ length: n }, (_, i) => triviaList[(days + i) % triviaList.length])
}
